export function getRecipe(benchmarkId: string): Recipe {
  const recipe = recipes.find((r) => r.benchmarkId === benchmarkId)
  if (!recipe) {
    throw new Error(`No recipe for benchmark id: ${benchmarkId}`)
  }
  return recipe
}
