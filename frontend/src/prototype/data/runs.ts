export function getRunsForCheckpoint(checkpointId: string, runs: readonly EvalRun[]): EvalRun[] {
  return runs.filter((run) => run.checkpointId === checkpointId)
}

export function getRunsForBenchmark(benchmarkId: string, runs: readonly EvalRun[]): EvalRun[] {
  return runs.filter((run) => run.benchmarkId === benchmarkId)
}

export function getPrimaryMetricResult(run: EvalRun, primaryMetricKey: string) {
  return run.metrics.find((metric) => metric.metricKey === primaryMetricKey) ?? null
}
