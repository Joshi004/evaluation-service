const ALL_BENCHMARK_DEFAULT_SOURCES: RunProfileSources = {
  sampling: 'benchmark_default',
  thinkHandling: 'benchmark_default',
  maxTokens: 'benchmark_default',
}

function standardResolvedProfile(benchmarkId: string): ResolvedProfile {
  const recipe = getRecipe(benchmarkId)
  return {
    temperature: recipe.defaultSampling.temperature,
    topP: recipe.defaultSampling.topP,
    topK: recipe.defaultSampling.topK,
    maxTokens: recipe.defaultMaxTokens,
    thinkHandling: recipe.defaultThinkHandling,
  }
}

// Shared shape for a run that used the active recipe and the
// benchmark-default source for every Layer 2 setting — the definition of
// `is_standard` from EVAL_SERVICE_PLAN.md Section 10.
function standardRunDefaults(benchmarkId: string) {
  return {
    profileSources: ALL_BENCHMARK_DEFAULT_SOURCES,
    resolvedProfile: standardResolvedProfile(benchmarkId),
    profileHash: BENCHMARK_DEFAULT_PROFILE_HASH[benchmarkId],
    recipeHash: getRecipe(benchmarkId).recipeHash,
    isStandard: true,
    isSmoke: false,
    flaggedReason: null,
  }
}

